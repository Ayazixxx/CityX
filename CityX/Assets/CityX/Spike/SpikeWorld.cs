using System.Collections.Generic;
using FishNet.Connection;
using FishNet.Managing;
using FishNet.Object;
using UnityEngine;

namespace CityX.Spike
{
    /// <summary>
    /// Populates the spike world with server-simulated entities.
    ///
    /// The agent "prefab" is built in code rather than authored as an asset.
    /// That keeps the whole spike self-contained and reviewable as text, and
    /// means the entity count is a number in a test rather than a scene to
    /// maintain.
    ///
    /// KNOWN LIMIT, stated rather than discovered later: runtime-registered
    /// prefabs only line up when server and client share one process (host
    /// mode), because both read the same collection instance. The moment the
    /// spike grows to a separate headless server and real client processes,
    /// this has to become a real prefab asset so both sides resolve the same
    /// prefab id. That is a known step, not a surprise.
    /// </summary>
    public class SpikeWorld : MonoBehaviour
    {
        /// <summary>
        /// PORT_PLAN's Phase 0 target. 200 is not arbitrary: it is roughly
        /// what dozens of players plus faction NPCs plus summons implies once
        /// every player is a source of extra entities.
        /// </summary>
        public const int DefaultAgentCount = 200;

        /// <summary>Spread agents over a disc rather than a point, so interest management has something to cull.</summary>
        public const float SpawnRadius = 100.0f;

        /// <summary>
        /// How far a player can see. THE number that makes scale possible:
        /// without it, every client receives every entity and bandwidth grows
        /// as players x entities, which is precisely the wall Godot hit and
        /// the reason this port exists.
        ///
        /// 40m against a 100m field means a player should observe roughly
        /// (40/100)^2 = 16% of the world, so the effect is large enough to
        /// measure unambiguously rather than argue about.
        /// </summary>
        public const float ObserverRadius = 40.0f;

        /// <summary>
        /// Resources paths of the prefabs generated by SpikeAssetBuilder.
        /// Kept here rather than in the builder so runtime does not depend on
        /// an editor-only assembly.
        /// </summary>
        public const string AgentResourcePath = "CityX.Spike/SpikeAgent";
        public const string PlayerResourcePath = "CityX.Spike/SpikePlayer";

        private NetworkManager _networkManager;
        private NetworkObject _agentPrefab;
        private NetworkObject _playerPrefab;
        private readonly List<NetworkObject> _spawned = new List<NetworkObject>();
        private readonly List<NetworkObject> _players = new List<NetworkObject>();

        /// <summary>How many agents are currently spawned by this world.</summary>
        public int SpawnedCount => _spawned.Count;

        public void Initialize(NetworkManager networkManager)
        {
            _networkManager = networkManager;
        }

        /// <summary>
        /// Spawns <paramref name="count"/> agents. Server only -- calling
        /// this on a client is a programming error, not a runtime condition,
        /// so it complains rather than silently doing nothing.
        /// </summary>
        public void SpawnAgents(int count)
        {
            if (_networkManager == null || !_networkManager.IsServerStarted)
            {
                Debug.LogError("[CityX.Spike] SpawnAgents called with no server running.");
                return;
            }

            EnsurePrefab();

            for (int i = 0; i < count; i++)
            {
                // Deterministic placement: a golden-angle spiral gives an even
                // disc without random clumping, so density is comparable
                // between runs with different entity counts.
                float t = (i + 0.5f) / count;
                float radius = SpawnRadius * Mathf.Sqrt(t);
                float angle = i * 2.39996323f;
                Vector3 position = new Vector3(Mathf.Cos(angle) * radius, 0.0f, Mathf.Sin(angle) * radius);

                NetworkObject agent = Object.Instantiate(_agentPrefab, position, Quaternion.identity);
                agent.gameObject.SetActive(true);
                _networkManager.ServerManager.Spawn(agent);
                _spawned.Add(agent);
            }
        }

        /// <summary>Despawns everything this world spawned. Safe to call twice.</summary>
        public void DespawnAll()
        {
            foreach (NetworkObject agent in _spawned)
            {
                if (agent != null && agent.IsSpawned && _networkManager != null && _networkManager.IsServerStarted)
                {
                    _networkManager.ServerManager.Despawn(agent);
                }
                else if (agent != null)
                {
                    Object.Destroy(agent.gameObject);
                }
            }
            _spawned.Clear();

            foreach (NetworkObject player in _players)
            {
                if (player != null && player.IsSpawned && _networkManager != null && _networkManager.IsServerStarted)
                {
                    _networkManager.ServerManager.Despawn(player);
                }
                else if (player != null)
                {
                    Object.Destroy(player.gameObject);
                }
            }
            _players.Clear();

            // The prefabs are shared project assets now, not objects this
            // world created, so they must NOT be destroyed here -- doing so
            // would delete them from disk in the editor.
            _agentPrefab = null;
            _playerPrefab = null;
        }

        /// <summary>
        /// Spawns a player presence owned by <paramref name="owner"/>. This is
        /// what interest management measures distance FROM -- without an owned
        /// object, a connection has no position and observes nothing.
        /// </summary>
        public NetworkObject SpawnPlayer(NetworkConnection owner, Vector3 position)
        {
            if (_networkManager == null || !_networkManager.IsServerStarted)
            {
                Debug.LogError("[CityX.Spike] SpawnPlayer called with no server running.");
                return null;
            }

            EnsurePlayerPrefab();

            NetworkObject player = Object.Instantiate(_playerPrefab, position, Quaternion.identity);
            player.gameObject.SetActive(true);
            _networkManager.ServerManager.Spawn(player, owner);
            _players.Add(player);
            return player;
        }

        private void EnsurePrefab()
        {
            if (_agentPrefab == null)
            {
                _agentPrefab = LoadAndRegister(AgentResourcePath);
            }
        }

        private void EnsurePlayerPrefab()
        {
            if (_playerPrefab == null)
            {
                _playerPrefab = LoadAndRegister(PlayerResourcePath);
            }
        }

        /// <summary>
        /// Loads a generated prefab and registers it so the server and every
        /// client resolve the same prefab id.
        ///
        /// These are real assets built by SpikeAssetBuilder rather than
        /// constructed here, for two reasons that only became visible once
        /// interest management was wired up: NetworkObserver's condition list
        /// is internal and can only be authored, and runtime-registered
        /// prefabs do not carry a stable id across separate processes. See
        /// that builder's class comment.
        /// </summary>
        private NetworkObject LoadAndRegister(string resourcePath)
        {
            GameObject asset = Resources.Load<GameObject>(resourcePath);
            if (asset == null)
            {
                Debug.LogError(
                    $"[CityX.Spike] missing generated prefab '{resourcePath}'. " +
                    "Run CityX > Spike > Rebuild Spike Assets, or call SpikeAssetBuilder.BuildAll.");
                return null;
            }

            NetworkObject nob = asset.GetComponent<NetworkObject>();
            if (nob == null)
            {
                Debug.LogError($"[CityX.Spike] generated prefab '{resourcePath}' has no NetworkObject.");
                return null;
            }

            _networkManager.SpawnablePrefabs.AddObject(nob, true, true);
            return nob;
        }
    }
}
